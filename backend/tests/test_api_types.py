"""The frontend's API types are what `make api-types` writes from the app's schema today, and
the writer stops on anything it was not written for."""

import copy
from pathlib import Path
from typing import Any

import pytest

from domain_health.api_types import (
    API_TYPES,
    UnknownSchemaError,
    declaration,
    generate,
    main,
    members,
    routes,
    schema,
    typescript,
)
from tests.paths import REPO


def test_the_committed_types_are_current() -> None:
    assert API_TYPES == REPO / "frontend" / "src" / "lib" / "api-types.ts"
    assert API_TYPES.exists(), "frontend/src/lib/api-types.ts is missing: run `make api-types`"
    committed = API_TYPES.read_text(encoding="utf-8")

    assert committed == generate(), (
        "frontend/src/lib/api-types.ts has drifted from the backend's schema: "
        "run `make api-types` and commit the file"
    )


def test_every_api_route_is_in_the_table_and_no_machine_route_is() -> None:
    listed = routes(schema())

    assert listed == [
        ("GET /api/clients", None, "ClientList"),
        ("POST /api/clients/{client_id}/handled", "Click", "ClientPage"),
        ("POST /api/clients/{client_id}/reopen", "Click", "ClientPage"),
        ("GET /api/clients/{client_id}/snapshot", None, "ClientPage"),
        ("POST /api/live-check", "LiveCheckRequest", "LiveCheckResult"),
    ]
    text = generate()
    for left_out in ("WorkerRun", "Dispatched", "HTTPValidationError", "Health", "any"):
        assert f" {left_out}" not in text, left_out


def test_the_file_says_it_is_generated_and_holds_only_types() -> None:
    text = generate()

    assert text.startswith("// Generated by `make api-types`")
    assert text.endswith("}\n")
    for line in text.splitlines():
        if line and not line.startswith((" ", "//", "}")):
            assert line.startswith(("export interface ", "export type ")), line


def test_each_construct_is_written_as_its_typescript() -> None:
    assert members({"type": "string", "format": "date"}, "x") == ["string"]
    assert members({"type": "integer", "minimum": 0}, "x") == ["number"]
    assert members({"anyOf": [{"type": "number"}, {"type": "null"}]}, "x") == ["number", "null"]
    assert members({"type": "string", "enum": ["a", "b"]}, "x") == ['"a"', '"b"']
    assert members({"type": "string", "const": "ok"}, "x") == ['"ok"']
    assert members({"$ref": "#/components/schemas/Fix"}, "x") == ["Fix"]
    assert members({"type": "array", "items": {"type": "string"}}, "x") == ["string[]"]
    both = {"anyOf": [{"type": "string"}, {"type": "integer"}]}
    assert members({"type": "array", "items": both}, "x") == ["(string | number)[]"]
    marks = {"type": "object", "additionalProperties": {"$ref": "#/components/schemas/Mark"}}
    assert members(marks, "x") == ["Record<string, Mark>"]


def test_a_field_is_optional_only_when_the_schema_does_not_require_it() -> None:
    thing = {
        "type": "object",
        "properties": {
            "always": {"type": "string"},
            "empty": {"anyOf": [{"type": "string"}, {"type": "null"}]},
            "maybe": {"type": "boolean", "default": False},
        },
        "required": ["always", "empty"],
        "additionalProperties": False,
    }

    assert declaration("Thing", thing, set()) == [
        [
            "export interface Thing {",
            "  always: string;",
            "  empty: string | null;",
            "  maybe?: boolean;",
            "}",
        ]
    ]


def test_a_long_list_of_literals_gets_a_name_and_one_member_to_a_line() -> None:
    words = [f"a_long_word_number_{n}" for n in range(8)]
    thing = {
        "type": "object",
        "properties": {"kinds": {"type": "array", "items": {"type": "string", "enum": words}}},
        "required": ["kinds"],
    }

    assert declaration("Thing", thing, set()) == [
        ["export interface Thing {", "  kinds: ThingKinds[];", "}"],
        ["export type ThingKinds =", *(f'  | "{w}"' for w in words[:-1]), f'  | "{words[-1]}";'],
    ]
    with pytest.raises(UnknownSchemaError, match="too long"):
        declaration("Thing", thing, {"ThingKinds"})


@pytest.mark.parametrize(
    "unknown",
    [
        {"type": "string", "pattern": "^a$"},
        {"oneOf": [{"type": "string"}]},
        {"allOf": [{"$ref": "#/components/schemas/Fix"}]},
        {"type": "array"},
        {"type": "array", "prefixItems": [{"type": "string"}], "items": {"type": "string"}},
        {"type": "object"},
        {"type": "object", "additionalProperties": True},
        {"type": "string", "format": "uuid"},
        {"type": "integer", "enum": [1, 2]},
        {"$ref": "#/elsewhere/Fix"},
        {},
    ],
)
def test_an_unknown_construct_stops_the_writer(unknown: dict[str, Any]) -> None:
    with pytest.raises(UnknownSchemaError):
        members(unknown, "x")


def test_an_unknown_construct_anywhere_in_the_schema_stops_the_whole_file() -> None:
    changed = copy.deepcopy(schema())
    changed["components"]["schemas"]["Click"]["properties"]["risk_id"]["pattern"] = "^a"

    with pytest.raises(UnknownSchemaError, match=r"Click\.risk_id.*pattern"):
        typescript(changed)

    free = copy.deepcopy(schema())
    free["components"]["schemas"]["Click"]["additionalProperties"] = True
    with pytest.raises(UnknownSchemaError, match="Click"):
        typescript(free)


def test_a_change_to_a_model_changes_the_file() -> None:
    changed = copy.deepcopy(schema())
    changed["components"]["schemas"]["Click"]["properties"]["note"] = {"type": "string"}

    assert typescript(changed) != generate()
    assert "  note?: string;" in typescript(changed)


def test_the_command_writes_the_file(tmp_path: Path) -> None:
    target = tmp_path / "lib" / "api-types.ts"

    assert main(target) == 0
    assert target.read_text(encoding="utf-8") == generate()
