"""`make api-types`: the API's types for the frontend, written from the app's own schema.

The schema is the one FastAPI builds from the models in `app.py`. Only what the frontend's
server calls is written: the request body and the 200 response of every `/api/*` route, and the
types those reach. The machine routes and FastAPI's own validation-error shape are left out.

The writer knows the constructs this schema uses and nothing more. One it does not know stops
the command with an error: it never writes `any`. The output is already in the frontend
formatter's style, so the committed file is exactly what this writes, and a test compares them.
The deployed service never imports this module.
"""

import json
import re
import sys
from pathlib import Path
from typing import Any

from domain_health.app import create_app
from domain_health.clock import FixedClock
from domain_health.risks.model import FixtureRiskModel
from domain_health.seeded.fallback import RUN_AT, WIDTH, offline_deps
from domain_health.seeded.recordings import REPO
from domain_health.store.memory import MemoryStore
from domain_health.worker import ModelFacts

API_TYPES = REPO / "frontend" / "src" / "lib" / "api-types.ts"
API_PREFIX = "/api/"
REF_PREFIX = "#/components/schemas/"

HEADER = """\
// Generated by `make api-types` from the backend's OpenAPI schema. Do not edit by hand.
// A backend test (`backend/tests/test_api_types.py`) fails when this file and the schema differ:
// change the models in `backend/src/domain_health/`, then run `make api-types`.
//
// Every `/api/*` route's request body and 200 response, and the types they reach. A date is a
// string like "2026-01-04"; a date and time is an ISO 8601 string with its offset.
"""

# Keys that say nothing about a value's TypeScript type: names, notes and limits on a value.
NOTES = {
    "title",
    "description",
    "default",
    "format",
    "minimum",
    "maximum",
    "exclusiveMinimum",
    "exclusiveMaximum",
    "maxLength",
    "minLength",
    "maxItems",
    "minItems",
}
PLAIN = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}
FORMATS = {"date", "date-time"}
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
METHODS = ("get", "post", "put", "patch", "delete")

Schema = dict[str, Any]


class UnknownSchemaError(Exception):
    """The schema uses something this writer was not written for."""


def _only(schema: Schema, allowed: set[str], where: str) -> None:
    extra = sorted(set(schema) - allowed - NOTES)
    if extra:
        raise UnknownSchemaError(f"{where}: this writer does not know {', '.join(extra)}")
    if schema.get("format", "date") not in FORMATS:
        raise UnknownSchemaError(f"{where}: this writer does not know format {schema['format']}")


def _literal(value: object, where: str) -> str:
    if not isinstance(value, str):
        raise UnknownSchemaError(f"{where}: a literal that is not a string: {value!r}")
    return json.dumps(value, ensure_ascii=False)


def _ref(schema: Schema, where: str) -> str:
    target = str(schema["$ref"])
    if not target.startswith(REF_PREFIX):
        raise UnknownSchemaError(f"{where}: a reference outside the components: {target}")
    return target.removeprefix(REF_PREFIX)


def members(schema: Schema, where: str) -> list[str]:
    """The TypeScript types a value of this schema may be: one, or the members of a union."""
    if "$ref" in schema:
        _only(schema, {"$ref"}, where)
        return [_ref(schema, where)]
    if "anyOf" in schema:
        _only(schema, {"anyOf"}, where)
        return [member for option in schema["anyOf"] for member in members(option, where)]
    if "enum" in schema:
        _only(schema, {"enum", "type"}, where)
        return [_literal(value, where) for value in schema["enum"]]
    if "const" in schema:
        _only(schema, {"const", "type"}, where)
        return [_literal(schema["const"], where)]
    kind = schema.get("type")
    if kind in PLAIN or kind == "null":
        _only(schema, {"type"}, where)
        return [PLAIN.get(kind, "null")]
    if kind == "array":
        _only(schema, {"type", "items"}, where)
        if "items" not in schema:
            raise UnknownSchemaError(f"{where}: a list that does not say what it holds")
        items = members(schema["items"], where)
        return [f"({' | '.join(items)})[]" if len(items) > 1 else f"{items[0]}[]"]
    if kind == "object" and "properties" not in schema:
        _only(schema, {"type", "additionalProperties"}, where)
        values = schema.get("additionalProperties")
        if not isinstance(values, dict):
            raise UnknownSchemaError(f"{where}: an object that does not say what it holds")
        return [f"Record<string, {' | '.join(members(values, where))}>"]
    raise UnknownSchemaError(f"{where}: this writer does not know {json.dumps(schema)}")


def _alias(name: str, options: list[str]) -> list[str]:
    """`export type`, on one line when it fits and one member to a line when it does not."""
    flat = f"export type {name} = {' | '.join(options)};"
    if len(flat) <= WIDTH:
        return [flat]
    broken = [f"  | {option}" for option in options]
    return [f"export type {name} =", *broken[:-1], f"{broken[-1]};"]


def _camel(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def declaration(name: str, schema: Schema, taken: set[str]) -> list[list[str]]:
    """One component as TypeScript: its own declaration, then any list of literals too long for
    a field's line, pulled out under a name of its own (`<Type><Field>`)."""
    if schema.get("type") != "object" or "properties" not in schema:
        return [_alias(name, members(schema, name))]
    _only(schema, {"type", "properties", "required", "additionalProperties"}, name)
    if schema.get("additionalProperties", False) is not False:
        raise UnknownSchemaError(f"{name}: named fields and free ones together")
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    pulled: list[list[str]] = []
    for field, value in schema["properties"].items():
        where = f"{name}.{field}"
        if not IDENTIFIER.fullmatch(field):
            raise UnknownSchemaError(f"{where}: a field name that is not a plain word")
        mark = "" if field in required else "?"
        line = f"  {field}{mark}: {' | '.join(members(value, where))};"
        if len(line) > WIDTH:
            items = value.get("items", {})
            own = f"{name}{_camel(field)}"
            if value.get("type") != "array" or "enum" not in items or own in taken:
                raise UnknownSchemaError(f"{where}: too long for one line, and not a list to name")
            taken.add(own)
            pulled.append(_alias(own, members(items, where)))
            line = f"  {field}{mark}: {own}[];"
        lines.append(line)
    return [[*lines, "}"], *pulled]


def _body(content: Schema | None, where: str) -> str | None:
    """The name of the type of a JSON body, or None when there is no body."""
    if content is None:
        return None
    schema = content.get("content", {}).get("application/json", {}).get("schema")
    if not isinstance(schema, dict) or "$ref" not in schema:
        raise UnknownSchemaError(f"{where}: a body that is not one named type")
    return _ref(schema, where)


def routes(openapi: Schema) -> list[tuple[str, str | None, str]]:
    """Every `/api/*` route as (`METHOD path`, request type, response type), in order."""
    found = []
    for path, operations in sorted(openapi["paths"].items()):
        if not path.startswith(API_PREFIX):
            continue
        for method in METHODS:
            if method not in operations:
                continue
            operation = operations[method]
            name = f"{method.upper()} {path}"
            response = _body(operation["responses"].get("200"), name)
            if response is None:
                raise UnknownSchemaError(f"{name}: no 200 response")
            found.append((name, _body(operation.get("requestBody"), name), response))
    return found


def _references(schema: object) -> set[str]:
    if isinstance(schema, dict):
        own = {_ref(schema, "a reference")} if "$ref" in schema else set()
        return own.union(*(_references(value) for value in schema.values()))
    if isinstance(schema, list):
        return set().union(*(_references(value) for value in schema))
    return set()


def reached(components: dict[str, Schema], start: set[str]) -> list[str]:
    """The named types the routes use, directly or through another type. Sorted."""
    seen: set[str] = set()
    todo = sorted(start)
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        if name not in components:
            raise UnknownSchemaError(f"the schema names {name} and does not define it")
        seen.add(name)
        todo += sorted(_references(components[name]))
    return sorted(seen)


def typescript(openapi: Schema) -> str:
    """The whole file's text for this schema."""
    components: dict[str, Schema] = openapi.get("components", {}).get("schemas", {})
    listed = routes(openapi)
    used = {name for _, request, response in listed for name in (request, response) if name}
    names = reached(components, used)
    taken = set(components) | {"ApiRoutes"}
    blocks = [block for name in names for block in declaration(name, components[name], taken)]
    table = ["export interface ApiRoutes {"]
    for route, request, response in listed:
        line = f"  {json.dumps(route)}: {{ request: {request or 'null'}; response: {response} }};"
        if len(line) > WIDTH:
            raise UnknownSchemaError(f"{route}: too long for one line of the route table")
        table.append(line)
    blocks.append(
        ["// Each route: the body it takes (null for none) and what a 200 gives.", *table, "}"]
    )
    return HEADER + "".join("\n" + "\n".join(block) + "\n" for block in blocks)


def schema() -> Schema:
    """The app's OpenAPI schema. The app is built from fakes; only its routes are read."""
    deps = offline_deps(
        store=MemoryStore(),
        clock=FixedClock(RUN_AT),
        model=FixtureRiskModel({}),
        facts=ModelFacts(prompt_version="none", model="none"),
    )
    return create_app(deps).openapi()


def generate() -> str:
    return typescript(schema())


def main(path: Path = API_TYPES) -> int:
    text = generate()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path.name}: {text.count('export ')} declarations")
    return 0


if __name__ == "__main__":
    sys.exit(main())
